// Generates public/assets/games-cover.svg — the Video Games hobby-panel cover:
// an 8-bit, black-and-white 80x45 pixel grid (20px cells -> 1600x900) of one
// arcade cabinet lit by its own CRT. Run with: node scripts/gen-games-cover.mjs
import { writeFileSync } from "node:fs";

const W = 80, H = 45, CELL = 20;
const grid = Array.from({ length: H }, () => Array(W).fill("."));

const put = (x, y, c) => {
  if (x >= 0 && x < W && y >= 0 && y < H) grid[y][x] = c;
};
const rect = (x0, y0, x1, y1, c) => {
  for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) put(x, y, c);
};

// ---- wall glow behind the cabinet (dithered ring, classic 8-bit shading) ----
const cx = 39.5, cy = 17;
for (let y = 0; y < 35; y++) {
  for (let x = 0; x < W; x++) {
    const d = Math.hypot((x - cx) * 0.75, y - cy); // squash: wider than tall
    if (d < 11) put(x, y, "G");
    else if (d < 14 && (x + y) % 2 === 0) put(x, y, "G");
    else if (d < 17 && (x + y) % 2 === 0) put(x, y, "g");
  }
}

// ---- neighbouring cabinets, barely lit ----
for (const x0 of [12, 56]) {
  rect(x0, 13, x0 + 11, 34, "n");
  rect(x0 + 2, 15, x0 + 9, 20, "m"); // their dead screens
}

// ---- floor ----
rect(0, 35, W - 1, H - 1, "f");
// light pool spilling from the screen (dithered ellipse)
for (let y = 35; y < H; y++) {
  for (let x = 0; x < W; x++) {
    const d = Math.hypot((x - cx) * 0.55, (y - 36) * 2.2);
    if (d < 6) put(x, y, "p");
    else if (d < 10 && (x + y) % 2 === 0) put(x, y, "p");
  }
}
// cabinet shadow line
rect(31, 35, 48, 35, "d");

// ---- the lit cabinet ----
rect(33, 8, 46, 34, "#");        // body
rect(35, 9, 44, 10, "+");        // marquee
rect(36, 9, 43, 9, "=");         // marquee catching glow
rect(34, 12, 45, 21, "+");       // screen bezel
for (let y = 13; y <= 20; y++)   // CRT with scanlines
  rect(35, y, 44, y, y % 2 ? "S" : "s");
rect(31, 22, 48, 24, "+");       // control deck (wider)
rect(31, 22, 48, 22, "=");       // deck top edge, lit
put(36, 21, "w");                // joystick ball
put(36, 22, "#");                // stick, dark against the lit deck edge
put(41, 23, "s"); put(43, 23, "s"); // buttons catching the screen light
rect(33, 25, 46, 34, "#");       // base
rect(37, 28, 42, 31, "+");       // coin door
put(38, 29, "d"); put(41, 29, "d"); // coin slots

// ---- emit SVG (horizontal runs merged) ----
const COLORS = {
  d: "#070707", f: "#141414", p: "#1d1d1d", n: "#111214", m: "#191b1e",
  g: "#131418", G: "#191b1f", "#": "#232323", "+": "#2f2f2f", "=": "#404040",
  S: "#e8e8e8", s: "#c2c2c2", w: "#dcdcdc",
};
let rects = "";
for (let y = 0; y < H; y++) {
  let x = 0;
  while (x < W) {
    const c = grid[y][x];
    let x2 = x;
    while (x2 + 1 < W && grid[y][x2 + 1] === c) x2++;
    if (c !== ".")
      rects += `<rect x="${x * CELL}" y="${y * CELL}" width="${(x2 - x + 1) * CELL}" height="${CELL}" fill="${COLORS[c]}"/>`;
    x = x2 + 1;
  }
  rects += "\n";
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice" shape-rendering="crispEdges">
<!-- The arcade after hours, as 8-bit black-and-white pixel art (matches the
     arcade page's monochrome look): one cabinet lit by its own CRT, dithered
     glow, dark neighbours. Generated by scripts/gen-games-cover.mjs; hand-editable
     as plain rects. -->
<rect width="1600" height="900" fill="#0b0b0b"/>
${rects}</svg>
`;
writeFileSync(new URL("../public/assets/games-cover.svg", import.meta.url), svg);
console.log("written");
